"""Tests for the HTML email template and the multipart message."""
from datetime import date

from services.email_service import build_message
from services.email_template import (
    build_email_html,
    safe_url,
    short_date,
    split_headline,
    split_sentences,
)

ARTICLES = [
    {"title": "Chips get faster - TechCrunch", "link": "https://example.com/a", "published": "Sun, 25 Oct 2026 04:00:00 GMT"},
    {"title": "<script>alert(1)</script> - Evil Site", "link": "javascript:alert(1)", "published": "garbage"},
]
INSIGHTS = "First point. Second point! Third point? Fourth point. Fifth point."


def test_headline_and_publisher_are_split():
    assert split_headline("Big news - The Verge") == ("Big news", "The Verge")
    assert split_headline("No publisher here") == ("No publisher here", "")


def test_dates_are_shortened_with_fallback():
    assert short_date("Sun, 25 Oct 2026 04:00:00 GMT") == "Oct 25"
    assert short_date("garbage") == "garbage"


def test_briefing_is_split_into_sentences():
    assert len(split_sentences(INSIGHTS)) == 5


def test_only_http_links_are_allowed():
    assert safe_url("https://x.com") == "https://x.com"
    assert safe_url("javascript:alert(1)") is None


def test_html_contains_content_and_disclosure():
    html = build_email_html(ARTICLES, INSIGHTS, "Generated by AI.", today=date(2026, 10, 26))
    assert "Chips get faster" in html and "TechCrunch" in html
    assert 'href="https://example.com/a"' in html
    assert "Generated by AI." in html
    assert "Monday, October 26, 2026" in html
    assert html.count("Fifth point.") == 1


def test_html_escapes_untrusted_text_and_drops_bad_links():
    html = build_email_html(ARTICLES, INSIGHTS, "d")
    assert "<script>" not in html
    assert "&lt;script&gt;" in html
    assert "javascript:" not in html


def test_message_has_plain_text_then_html():
    msg = build_message("plain body", "<p>html body</p>")
    assert msg.get_content_type() == "multipart/alternative"
    assert [p.get_content_type() for p in msg.get_payload()] == ["text/plain", "text/html"]


def test_message_without_html_is_plain_text():
    assert build_message("plain body").get_content_type() == "text/plain"