"""Tests for the agent's tools (agents/tools.py) — no LLM or network needed."""
import pytest

from agents import memory, tools

ARTICLES = [{"title": "Chip news", "link": "http://x/1", "published": "Mon"}]


@pytest.fixture(autouse=True)
def clean_state(tmp_path, monkeypatch):
    tools.reset_run_state()
    monkeypatch.setattr(memory, "DIGEST_FILE", tmp_path / "digests.json")
    monkeypatch.setattr(tools, "fetch_ai_articles", lambda **kw: list(ARTICLES))
    yield
    tools.reset_run_state()


def test_tools_have_descriptions_and_schemas():
    for t in tools.TOOLS:
        assert t.description, t.name
    assert "query" in tools.search_knowledge_base.args
    assert "insights" in tools.save_draft.args


def test_save_draft_needs_headlines_first():
    result = tools.save_draft.invoke({"insights": "A long enough analysis sentence."})
    assert result.startswith("Error")
    assert tools.current_draft() is None


def test_save_draft_builds_email_with_links_and_ai_disclosure():
    tools.fetch_ai_news.invoke({})
    result = tools.save_draft.invoke({"insights": "Five sentences of analysis go here."})

    draft = tools.current_draft()
    assert "human will review" in result
    assert "http://x/1" in draft["body"]               # links come from code, not the LLM
    assert "generated by AI" in draft["body"]          # disclosure
    assert draft["headlines"] == ["Chip news"]


def test_previous_digests_tool_reads_long_term_memory():
    assert "No previous digests" in tools.get_previous_digests.invoke({})
    memory.save_digest("Yesterday's trends.", ["h"])
    assert "Yesterday's trends." in tools.get_previous_digests.invoke({})


def test_agent_has_no_tool_that_sends_email():
    assert all("send" not in t.name for t in tools.TOOLS)


def test_knowledge_base_searches_are_capped_in_code(monkeypatch):
    import services.rag_service as rag
    monkeypatch.setattr(rag, "retrieve_relevant_news", lambda q: [])
    results = [tools.search_knowledge_base.invoke({"query": f"topic {i}"}) for i in range(tools.MAX_SEARCHES_PER_RUN + 1)]
    assert all("Search limit reached" not in r for r in results[:-1])
    assert "Search limit reached" in results[-1]
